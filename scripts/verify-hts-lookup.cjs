// Uses real local HTS data. Only failure/stale-response and admin sync UI
// boundaries are intercepted; this script never sends mail or updates live data.
const { chromium } = require('../frontend/topic-template/node_modules/@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

async function run() {
  const origin = process.env.HTS_TEST_ORIGIN || 'http://127.0.0.1:8180'
  const base = origin + '/preview/global/tools/hts-code-lookup'
  const adminOrigin = process.env.HTS_ADMIN_TEST_ORIGIN || 'http://127.0.0.1:8186'
  const output = path.resolve(__dirname, '../.impeccable/review/hts')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined, headless: true, args: ['--no-proxy-server'] })
  const report = { data: 'real embedded USITC snapshot', checks: [], performance: [], errors: [], failedAssets: [], screenshots: [] }
  const check = text => report.checks.push(text)
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin })
    const page = await context.newPage()
    page.on('pageerror', e => report.errors.push(e.message))
    page.on('response', r => { if (r.url().startsWith(origin + '/assets/') && r.status() >= 400) report.failedAssets.push({ url: r.url(), status: r.status() }) })
    let searches = 0
    page.on('request', r => { if (new URL(r.url()).pathname === '/api/public/hts-search') searches++ })
    await page.goto(base, { waitUntil: 'networkidle' })
    const input = page.locator('#hts-query'), rows = page.locator('.hts-table tbody tr')
    await page.waitForFunction(() => document.querySelector('[data-hts-form]') && document.querySelector('[data-hts-clear]').hidden)
    assert.match(await page.locator('[data-hts-output]').innerText(), /Find a customs code for your product/)
    assert.equal(await page.locator('header a[href$="/tools/hts-code-lookup"]').count(), 0)
    assert((await page.locator('footer a[href$="/tools/hts-code-lookup"]').count()) > 0)
    check('English initial state, existing header and footer-only entry')
    const before = searches
    await input.pressSequentially('8517130000', { delay: 40 })
    assert.equal(searches, before, 'must debounce while typing')
    await page.waitForFunction(() => document.querySelector('.hts-code')?.textContent === '8517.13.00.00')
    assert.equal(searches, before + 1)
    assert.equal(await rows.count(), 1)
    assert.match(await rows.first().innerText(), /Smartphones/)
    assert.equal(await page.locator('.hts-rate').innerText(), 'Free')
    await page.locator('[data-hts-copy]').click()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '8517130000')
    assert.match(await page.locator('[data-hts-toast]').innerText(), /Copied 8517130000/)
    check('300 ms debounce makes one request; exact result and real clipboard copy')
    await page.locator('[data-hts-clear]').click()
    assert.equal(await rows.count(), 0)
    assert.equal(new URL(page.url()).search, '')
    check('Clear removes old results and query')
    async function query(q, expected) {
      await input.fill(q)
      await page.locator('.hts-primary').click()
      await page.waitForFunction(q => document.querySelector('[data-hts-error]')?.hidden && document.querySelector('[data-hts-output]')?.getAttribute('aria-busy') === 'false' && new URL(location.href).searchParams.get('q') === q && !document.querySelector('.hts-pending'), q)
      if (expected) assert.match(await page.locator('[data-hts-output]').innerText(), expected)
    }
    await query('8517140020', /From 8517\.14\.00/)
    assert.equal(await page.locator('.hts-rate').innerText(), 'Free')
    check('Inherited rate exposes the correct parent source')
    await query('0101')
    assert((await page.locator('.hts-code').allTextContents()).every(code => code.startsWith('0101.')))
    await query('cotton t-shirts')
    assert((await rows.count()) > 0)
    await query('lithium ion')
    assert((await rows.count()) > 0)
    check('Leading zeros and real English full-text keywords')
    await query('84')
    assert.equal(await rows.count(), 25)
    const first = await page.locator('.hts-code').first().innerText()
    await page.locator('[data-hts-page="2"]').click()
    await page.waitForFunction(() => document.querySelector('.hts-pagination')?.textContent.includes('Page 2') && document.querySelector('[data-hts-output]').getAttribute('aria-busy') === 'false')
    assert.notEqual(await page.locator('.hts-code').first().innerText(), first)
    assert.equal(new URL(page.url()).searchParams.get('page'), '2')
    await page.goBack()
    await page.waitForFunction(() => document.querySelector('.hts-pagination')?.textContent.includes('Page 1') && !document.querySelector('.hts-pending'))
    check('25-result pagination and browser back restore the query/page')
    await query('noSuchProductZZZ', /No matching codes found/)
    assert.equal(await rows.count(), 0)
    check('No-match guidance without stale records')

    await page.route('**/api/public/hts-search?**', async route => {
      const q = new URL(route.request().url()).searchParams.get('q')
      if (q === '8517') {
        const result = await route.fetch()
        await new Promise(resolve => setTimeout(resolve, 900))
        await route.fulfill({ response: result }).catch(() => {})
      } else await route.continue()
    })
    await input.fill('8517'); await page.locator('.hts-primary').click()
    await page.waitForTimeout(80)
    await input.fill('6109'); await page.locator('.hts-primary').click()
    await page.waitForFunction(() => document.querySelector('.hts-code')?.textContent.startsWith('6109.'))
    await page.waitForTimeout(1100)
    assert((await page.locator('.hts-code').allTextContents()).every(code => code.startsWith('6109.')))
    await page.unroute('**/api/public/hts-search?**')
    check('Delayed older request cannot replace newer search results')
    await page.route('**/api/public/hts-search?**', route => route.fulfill({ status: 503, json: { error: 'Tariff data is temporarily unavailable. Try again shortly.' } }))
    await input.fill('8517'); await page.locator('.hts-primary').click()
    await page.locator('[data-hts-error]').waitFor({ state: 'visible' })
    assert.equal(await rows.count(), 0)
    assert.match(await page.locator('[data-hts-error]').innerText(), /temporarily unavailable/)
    await page.unroute('**/api/public/hts-search?**')
    await query('8517130000', /Smartphones/)
    check('503 recovery shows English guidance and removes stale results (intercepted boundary)')
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw Error('denied') } } }))
    await page.locator('[data-hts-copy]').click()
    assert.equal(await page.locator('.hts-copy-manual input').inputValue(), '8517130000')
    assert.equal(await page.locator('.hts-copy-manual input').evaluate(el => el.selectionEnd - el.selectionStart), 10)
    check('Denied clipboard reveals selected manual-copy field')

    // Fresh navigation keeps transient test toasts/manual fallback out of captures.
    await page.goto(base + '?q=8517140020', { waitUntil: 'networkidle' })
    await page.locator('.hts-legal summary').click()
    for (const [name, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]]) {
      await page.setViewportSize({ width, height })
      await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
      await page.waitForTimeout(180)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`)
      const file = path.join(output, name + '.png')
      await page.screenshot({ path: file, fullPage: true })
      report.screenshots.push(file)
    }
    for (const width of [320, 768]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`)
    }
    check('Desktop/mobile captures and no horizontal overflow at 320/390/768/1440')
    const nojs = await browser.newContext({ javaScriptEnabled: false })
    const ssr = await nojs.newPage()
    await ssr.goto(base + '?q=8517130000')
    assert.match(await ssr.locator('.hts-table').innerText(), /Smartphones/)
    await ssr.goto(base + '?q=84')
    await ssr.locator('[data-hts-page="2"]').click()
    assert.match(await ssr.locator('.hts-pagination').innerText(), /Page 2/)
    await nojs.close()
    check('No-JavaScript search and real page links work')
    for (const q of ['8517130000', '8517', 'cotton t-shirts', 'lithium ion', '0101', '84']) {
      const start = performance.now()
      const res = await context.request.get(origin + '/api/public/hts-search?q=' + encodeURIComponent(q))
      const json = await res.json()
      assert.equal(res.status(), 200)
      const ms = Math.round((performance.now() - start) * 10) / 10
      report.performance.push({ query: q, ms, matches: json.total })
      assert(ms < 200, `warm API response exceeds 200ms: ${q} ${ms}`)
    }
    check('All six warm real-data API samples are below 200 ms including local HTTP round trip')

    if (!process.env.HTS_SKIP_ADMIN) {
      const stateFile = path.resolve(__dirname, '../.tmp/hts/admin-review/browser-state.json')
      const adminContext = await browser.newContext(fs.existsSync(stateFile) ? { storageState: stateFile, viewport: { width: 1440, height: 1000 } } : { viewport: { width: 1440, height: 1000 } })
      const admin = await adminContext.newPage()
      admin.on('pageerror', e => report.errors.push('admin: ' + e.message))
      await admin.goto(adminOrigin + '/setup')
      if (await admin.locator('input[name=password_confirm]').count()) {
        const password = crypto.randomBytes(24).toString('base64url') + 'Aa1!'
        await admin.fill('[name=username]', 'hts-qa-owner')
        await admin.fill('[name=display_name]', 'HTS QA')
        await admin.fill('[name=email]', 'hts-qa@example.invalid')
        await admin.fill('[name=password]', password)
        await admin.fill('[name=password_confirm]', password)
        await admin.locator('form button[type=submit]').click()
        await admin.waitForURL(/\/(login|admin)/)
        if (new URL(admin.url()).pathname === '/login') {
          await admin.fill('[name=username]', 'hts-qa-owner'); await admin.fill('[name=password]', password)
          await admin.locator('form button[type=submit]').click()
          await admin.waitForURL(/\/admin/)
        }
        await adminContext.storageState({ path: stateFile })
      }
      await admin.goto(adminOrigin + '/admin#/admin/settings?section=hts')
      await admin.locator('[data-hts-sync]').waitFor()
      assert.match(await admin.locator('.hts-admin').innerText(), /2026 HTS Revision 22/)
      assert.match(await admin.locator('.hts-admin').innerText(), /19,949/)
      const statusResponse = await adminContext.request.get(adminOrigin + '/api/v1/system/hts')
      const status = await statusResponse.json()
      assert.equal(status.status.entries, 19949)
      await admin.route('**/api/v1/system/hts/sync', route => route.fulfill({ status: 202, json: { queued: true, message: 'QA task accepted' } }))
      let polls = 0
      await admin.route('**/api/v1/system/hts', route => route.fulfill({ json: { ...status, status: { ...status.status, running: ++polls === 1 } } }))
      await admin.locator('[data-hts-sync]').click()
      await admin.waitForFunction(() => document.querySelector('[data-hts-sync]')?.disabled === true)
      await admin.waitForFunction(() => document.querySelector('[data-hts-sync]')?.disabled === false)
      await admin.unroute('**/api/v1/system/hts/sync'); await admin.unroute('**/api/v1/system/hts')
      await admin.locator('[data-hts-refresh]').click()
      await admin.waitForTimeout(200)
      await admin.evaluate(() => window.scrollTo(0, 0))
      const screenshot = path.join(output, 'admin.png')
      await admin.screenshot({ path: screenshot, fullPage: true })
      report.screenshots.push(screenshot)
      check('Isolated admin real version/permissions; async sync/poll UI uses intercepted boundary without updating official data or sending mail')
      await adminContext.close()
    }
    assert.deepEqual(report.errors, [])
    assert.deepEqual(report.failedAssets, [])
    fs.writeFileSync(path.join(output, 'browser-report.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report, null, 2))
  } finally { await browser.close() }
}
run().catch(err => { console.error(err); process.exitCode = 1 })
