const { chromium } = require('../frontend/topic-template/node_modules/@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

async function run() {
  const origin = 'http://127.0.0.1:8180'
  const base = origin + '/preview/global/tools/hts-code-lookup'
  const output = path.resolve(__dirname, '../.impeccable/review/hts-detail')
  fs.mkdirSync(output, { recursive: true })
  const report = { checks: [], errors: [], failedAssets: [], widths: [], screenshots: [] }
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin })
    const page = await context.newPage()
    page.on('pageerror', e => report.errors.push(e.message))
    page.on('response', r => { if (r.url().startsWith(origin+'/assets/') && r.status() >= 400) report.failedAssets.push(r.url()) })
    assert.equal((await page.goto(base+'/3909505000', { waitUntil: 'networkidle' })).status(), 200)
    const root = page.locator('[data-hts-detail]')
    await page.waitForFunction(() => !document.querySelector('[data-copy-code]').disabled)
    const text = await root.innerText()
    for (const value of ['Other polyurethanes, in primary forms', '6.3%', 'Free (A*,AU', '15.4¢/kg + 51.5%', '2026 HTS Revision 22']) assert(text.includes(value), value)
    assert(!text.includes('Design preview'))
    assert.equal(await page.locator('header a[href$="/tools/hts-code-lookup"]').count(), 0)
    report.checks.push('Real official General / Special / Column 2 values, legal hierarchy and snapshot metadata; existing header')
    await page.locator('[data-copy-code]').click()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '3909505000')
    report.checks.push('Actual clipboard copy')
    await page.locator('#htd-origin').selectOption('CN')
    assert.match(await page.locator('[data-origin-message]').innerText(), /Section 301/)
    await page.locator('#htd-origin').selectOption('CA')
    assert.match(await page.locator('[data-origin-message]').innerText(), /USMCA/)
    await page.locator('#htd-origin').selectOption('')
    report.checks.push('Origin-specific official guidance switches without claiming total duties')
    await page.locator('.side-nav a[href="#classification"]').click()
    await page.waitForFunction(() => document.querySelector('.side-nav a[href="#classification"]').getAttribute('aria-current') === 'location')
    assert((await page.locator('#classification').boundingBox()).y >= 80)
    report.checks.push('Contents anchors clear the shared header and update current location')
    await page.locator('#htd-query').fill('8517.13.00.00')
    await page.locator('.search-box button').click()
    await page.waitForURL(base+'/8517130000')
    assert.match(await page.locator('.product-name').innerText(), /Smartphones/)
    assert.equal(await page.locator('.us-rates .rate').innerText(), 'Free')
    await page.locator('#htd-query').fill('cotton t-shirts')
    await page.locator('.search-box button').click()
    await page.waitForURL(/\?q=cotton/)
    const href = await page.locator('.hts-code').first().getAttribute('href')
    assert(href.startsWith('/preview/global/tools/hts-code-lookup/'))
    await page.locator('.hts-code').first().click()
    await page.waitForSelector('[data-hts-detail]')
    report.checks.push('Dotted exact code opens detail; English product search opens real results and working detail links')
    await page.goto(base+'?q=8517140020', { waitUntil: 'networkidle' })
    await page.locator('#hts-query').fill('3909505000')
    await page.waitForFunction(() => document.querySelector('.hts-code')?.textContent.includes('3909.50.50.00'))
    assert.equal(await page.locator('.hts-code').getAttribute('href'), '/preview/global/tools/hts-code-lookup/3909505000')
    report.checks.push('Debounced results preserve preview base in detail links')
    await page.goto(base+'/3909505000', { waitUntil: 'networkidle' })
    await page.waitForFunction(() => !document.querySelector('[data-copy-code]').disabled)
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.evaluate(() => scrollTo(0,0))
      const dimensions = await page.evaluate(() => ({ view:innerWidth, document:document.documentElement.scrollWidth, body:document.body.scrollWidth, code:document.querySelector('.commodity-code').getBoundingClientRect().width, table:document.querySelector('.us-rates').getBoundingClientRect().width }))
      report.widths.push({ width, ...dimensions })
      assert(dimensions.document <= width+1 && dimensions.body <= width+1, 'Horizontal overflow at '+width)
      if (width === 390 || width === 1440) {
        const file = path.join(output, width === 1440 ? 'desktop.png' : 'mobile.png')
        await page.screenshot({ path: file, fullPage: true, animations: 'disabled' })
        report.screenshots.push(file)
      }
    }
    await page.setViewportSize({ width:1440, height:2164 })
    await page.evaluate(() => scrollTo(0,0))
    await page.screenshot({ path:path.join(output,'comp-viewport.png'), animations:'disabled' })
    report.screenshots.push(path.join(output,'comp-viewport.png'))
    report.checks.push('320 / 390 / 768 / 1440 layouts have no page overflow')
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => { throw Error('Denied') } }, configurable:true }))
    await page.locator('[data-copy-code]').click()
    assert.equal(await page.locator('.copy-manual input').inputValue(), '3909505000')
    assert.match(await page.locator('[data-copy-toast]').innerText(), /manual copying/)
    report.checks.push('Clipboard denial exposes selected manual-copy field')
    for (const invalid of ['0000000000','1234']) {
      assert.equal((await page.goto(base+'/'+invalid)).status(), 404)
      assert.match(await page.locator('h1').innerText(), /HTS code not found/)
      assert.equal(await page.locator('a:has-text("Search customs codes")').getAttribute('href'), '/preview/global/tools/hts-code-lookup')
    }
    report.checks.push('Invalid and absent codes return English 404 with search recovery')
    const nojs = await browser.newContext({ javaScriptEnabled:false, viewport:{width:1440,height:1000} })
    const nojsPage = await nojs.newPage()
    await nojsPage.goto(base+'/3909505000')
    assert.match(await nojsPage.locator('.us-rates').innerText(), /6.3%/)
    assert.equal(await nojsPage.locator('[data-origin-controls]').isVisible(), false)
    await nojsPage.locator('#htd-query').fill('8517130000')
    await nojsPage.locator('.search-box button').click()
    assert.match(await nojsPage.locator('.hts-code').innerText(), /8517.13.00.00/)
    report.checks.push('No-JavaScript legal data, search submission and result links work')
    assert.deepEqual(report.errors, [])
    assert.deepEqual(report.failedAssets, [])
    fs.writeFileSync(path.join(output,'verification.json'),JSON.stringify(report,null,2))
    console.log(JSON.stringify(report,null,2))
  } finally { await browser.close() }
}
run().catch(e=>{console.error(e);process.exitCode=1})
